ORIGIN = "http://127.0.0.1:5178"


class StorageAndConfigurationTests(TestCase):
    def setUp(self):
        self.directory = Path(self.enterContext(tempfile.TemporaryDirectory()))
        self.store = SiteStore(self.directory / "sites.sqlite3")
        self.store.initialize()

    def test_existing_pbkdf2_credential_and_site_survive_initialization(self):
        # Fixture generated by the original framework before removing its dependency.
        site = Site(name="Existing site", key="site_legacy", origins=[ORIGIN], actions=["register"],
                    secret_hash="pbkdf2_sha256$1000000$migration-fixture$9qs5ALBD707GKAw4MW5YNNkGyF7e7yFNdEt+mMdVMG4=")
        self.store.create(site)
        self.store.initialize()
        restored = self.store.get_active(site.key)
        self.assertEqual(restored.origins, [ORIGIN])
        self.assertTrue(restored.accepts_secret("starlock-legacy-test"))
        self.assertFalse(restored.accepts_secret("incorrect"))
        self.assertIsNone(self.store.get("' OR 1=1 --"))

    def test_new_hash_and_unusable_hash(self):
        site = Site(name="Test")
        self.assertFalse(site.accepts_secret("anything"))
        site.set_secret("local-unit-test-value")
        self.assertTrue(site.accepts_secret("local-unit-test-value"))
        self.assertFalse(site.accepts_secret("other-value"))
        site.secret_hash = "pbkdf2_sha256$not-an-integer$salt$value"
        self.assertFalse(site.accepts_secret("anything"))

    def test_configuration_requires_secret_and_hides_demo_outside_debug(self):
        with self.assertRaises(RuntimeError):
            Settings()
        with self.assertRaises(RuntimeError):
            Settings(secret_key=DEVELOPMENT_KEY)
        with patch.dict(os.environ, {"STARLOCK_DEBUG": "0", "STARLOCK_DEMO": "1",
                                      "STARLOCK_SECRET_KEY": "local-test-production-config"}, clear=True):
            settings = Settings.from_env()
        self.assertFalse(settings.demo_enabled)
        with TestClient(create_app(replace(settings, database_path=self.store.path), self.store)) as client:
            self.assertEqual(client.get("/docs").status_code, 404)
            self.assertEqual(client.get("/openapi.json").status_code, 404)
            self.assertEqual(client.post("/demo/session", json={}).status_code, 404)

    def test_cli_private_credential_and_disable(self):
        environment = {"STARLOCK_DEBUG": "1", "STARLOCK_DATABASE_PATH": str(self.store.path)}
        arguments = ["cli.py", "create-site", "--name", "CLI test", "--origin", ORIGIN, "--action", "register"]
        output = io.StringIO()
        with patch.dict(os.environ, environment), patch("sys.argv", arguments), \
             patch("cli.Path.home", return_value=self.directory), contextlib.redirect_stdout(output):
            cli.main()
        files = list((self.directory / ".local/share/starlock/credentials").glob("*.json"))
        self.assertEqual(len(files), 1)
        self.assertEqual(stat.S_IMODE(files[0].stat().st_mode), 0o600)
        credential = json.loads(files[0].read_text())
        self.assertNotIn(credential["site_secret"], output.getvalue())
        self.assertTrue(self.store.get_active(credential["site_key"]).accepts_secret(credential["site_secret"]))
        with patch.dict(os.environ, environment), patch("sys.argv", ["cli.py", "set-site-types", credential["site_key"],
             "--challenge-type", "slider", "--challenge-type", "bezier_slider"]), contextlib.redirect_stdout(io.StringIO()):
            cli.main()
        self.assertEqual(self.store.get_active(credential["site_key"]).challenge_types, ["slider", "bezier_slider"])
        with patch.dict(os.environ, environment), patch("sys.argv", ["cli.py", "disable-site", credential["site_key"]]), \
             contextlib.redirect_stdout(io.StringIO()):
            cli.main()
        self.assertFalse(self.store.get(credential["site_key"]).active)


class DemoIntegrationTests(TestCase):
    def setUp(self):
        directory = Path(self.enterContext(tempfile.TemporaryDirectory()))
        settings = Settings(debug=True, demo_enabled=True, database_path=directory / "sites.sqlite3",
                            redis_prefix="starlock:test:" + secrets.token_hex(8) + ":")
        self.app = create_app(settings)
        self.service = self.app.state.service
        self.service.redis.ping()
        self.addCleanup(self.clean_keys)
        self.client = self.enterContext(TestClient(self.app))
        generated = replace(generate("text"), answer="ABCDE")
        self.enterContext(patch("verification.service.generate", return_value=generated))

    def clean_keys(self):
        keys = list(self.service.redis.scan_iter(self.service.prefix + "*"))
        if keys:
            self.service.redis.delete(*keys)

    def test_hosted_demo_does_not_rewrite_the_existing_demo_site(self):
        original = Site(key="site_local_demo", name="Original demo", origins=[ORIGIN], actions=["demo_submit"])
        self.service.sites.save(original)
        remote_origin = "http://127.0.0.1:5179"
        session = self.client.post("/demo/session", json={"challenge_type": "text"}, headers={"Origin": remote_origin})
        self.assertEqual(session.status_code, 201)
        self.assertEqual(session.json()["site_key"], "site_local_hosted_demo")
        self.assertEqual(self.service.sites.get_active(original.key).origins, [ORIGIN])
        browser = {"site_key": session.json()["site_key"], "session_ticket": session.json()["session_ticket"]}
        challenge = self.client.post("/v1/challenges", json=browser, headers={"Origin": remote_origin})
        result = self.client.post(f'/v1/challenges/{challenge.json()["challenge_id"]}/verify',
                                  json={**browser, "answer": "ABCDE"}, headers={"Origin": remote_origin})
        passed = self.client.post("/demo/submit", json={"token": result.json()["verification_token"]},
                                  headers={"Origin": remote_origin})
        self.assertTrue(passed.json()["success"])

    def passed(self):
        session = self.client.post("/demo/session", json={"challenge_type": "text"}, headers={"Origin": ORIGIN})
        self.assertEqual(session.status_code, 201)
        self.assertIn("HttpOnly", session.headers["set-cookie"])
        self.assertIn("SameSite=strict", session.headers["set-cookie"])
        browser = {key: session.json()[key] for key in ("site_key", "session_ticket")}
        challenge = self.client.post("/v1/challenges", json=browser, headers={"Origin": ORIGIN}).json()
        response = self.client.post(f'/v1/challenges/{challenge["challenge_id"]}/verify',
                                    json={**browser, "answer": "ABCDE"}, headers={"Origin": ORIGIN})
        self.assertEqual(response.status_code, 200)
        return response.json()["verification_token"]

    def test_demo_business_consumes_once(self):
        token = self.passed()
        result = self.client.post("/demo/submit", json={"token": token}, headers={"Origin": ORIGIN})
        self.assertEqual(result.status_code, 200)
        self.assertTrue(result.json()["success"])
        duplicate = self.client.post("/demo/submit", json={"token": token}, headers={"Origin": ORIGIN})
        self.assertEqual(duplicate.json()["error_code"], "TOKEN_USED")

    def test_other_browser_context_cannot_consume_token(self):
        token = self.passed()
        with TestClient(self.app) as other:
            other.post("/demo/session", json={"challenge_type": "text"}, headers={"Origin": ORIGIN})
            result = other.post("/demo/submit", json={"token": token}, headers={"Origin": ORIGIN})
            self.assertEqual(result.json()["error_code"], "CONTEXT_MISMATCH")
        result = self.client.post("/demo/submit", json={"token": token}, headers={"Origin": ORIGIN})
        self.assertEqual(result.status_code, 200)

    def test_origin_and_tampered_cookie_are_rejected(self):
        result = self.client.post("/demo/session", json={"challenge_type": "text"}, headers={"Origin": "https://evil.example"})
        self.assertEqual(result.status_code, 403)
        token = self.passed()
        self.client.cookies.clear()
        self.client.cookies.set("starlock_demo_context", "tampered", path="/demo/")
        result = self.client.post("/demo/submit", json={"token": token}, headers={"Origin": ORIGIN})
        self.assertEqual(result.json()["error_code"], "CONTEXT_MISMATCH")
